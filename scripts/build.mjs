import { build } from 'esbuild';
import { mkdir, writeFile } from 'node:fs/promises';

const { outputFiles } = await build({
  entryPoints: ['src/index.ts'],
  bundle: true,
  format: 'esm',
  target: 'es2022',
  charset: 'utf8',
  legalComments: 'none',
  banner: { js: '// Generated from src/index.ts by npm run build. Do not edit this file directly.' },
  write: false,
});

await mkdir('dist', { recursive: true });
for (const path of ['index.js', 'dist/_worker.js']) {
  await writeFile(path, outputFiles[0].contents);
}
